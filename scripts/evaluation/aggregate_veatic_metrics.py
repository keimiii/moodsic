#!/usr/bin/env python3
"""Aggregate VEATIC inference runs into evaluation-ready tables.

This script expects the consolidated Parquet summary produced by
``scripts/evaluation/run_inference_pipeline.py`` (files matching
``results/inference/pipeline_*.parquet``). Pick the desired run and pass its
path as the first argument to regenerate the per-video and aggregate CSV
exports, plus a companion JSON blob capturing the parameter set used for the
markdown summaries.

Example
-------
Run inside the project virtualenv after generating a pipeline summary::

    source .venv/bin/activate.fish
    python scripts/evaluation/aggregate_veatic_metrics.py \
        results/inference/pipeline_results_20251005_161034.parquet

To compare different runs, point the positional argument at another
``pipeline_*.parquet`` file from ``results/inference`` (shell globs like
``pipeline_results_2025*.parquet`` work too if they resolve to a single
artifact).
"""

import argparse
import csv
import json
import math
import random
import statistics
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, MutableMapping, Optional, Tuple

import pyarrow.parquet as pq

PATHWAYS = ("scene", "face", "fusion")
METRICS = ("valence", "arousal")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "summary_parquet",
        type=Path,
        help="Parquet export generated by run_inference_pipeline.py.",
    )
    parser.add_argument(
        "--labels-dir",
        type=Path,
        default=Path("data/VEATIC/rating_averaged"),
        help="Directory containing VEATIC averaged rating CSVs.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/evaluation"),
        help="Directory where aggregate CSV outputs will be written.",
    )
    parser.add_argument(
        "--bootstrap-samples",
        type=int,
        default=1000,
        help="Number of bootstrap samples for confidence intervals.",
    )
    parser.add_argument(
        "--ci",
        type=float,
        default=0.95,
        help="Confidence interval level (e.g., 0.95 for 95%%).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=20240209,
        help="Random seed for bootstrap resampling.",
    )
    parser.add_argument(
        "--timestamp",
        type=str,
        default=None,
        help="Override timestamp portion of output filenames.",
    )
    return parser.parse_args()


def load_ground_truth_means(labels_dir: Path, video_id: str) -> Dict[str, float]:
    means: Dict[str, float] = {}
    for metric in METRICS:
        label_path = labels_dir / f"{video_id}_{metric}.csv"
        if not label_path.exists():
            raise FileNotFoundError(f"Missing label file: {label_path}")
        total = 0.0
        count = 0
        with label_path.open("r", encoding="utf-8") as handle:
            reader = csv.reader(handle)
            for row in reader:
                if not row:
                    continue
                try:
                    total += float(row[1])
                    count += 1
                except (IndexError, ValueError) as exc:
                    raise ValueError(f"Malformed label row in {label_path}: {row}") from exc
        if count == 0:
            raise ValueError(f"No label rows found in {label_path}")
        means[metric] = total / count
    return means


def decode_metadata(metadata: Optional[Mapping[bytes, bytes]]) -> Dict[str, str]:
    if not metadata:
        return {}
    decoded: Dict[str, str] = {}
    for key, value in metadata.items():
        decoded_key = key.decode("utf-8", errors="ignore") if isinstance(key, bytes) else str(key)
        decoded_value = (
            value.decode("utf-8", errors="ignore") if isinstance(value, bytes) else str(value)
        )
        decoded[decoded_key] = decoded_value
    return decoded


def load_pipeline_runs(parquet_path: Path) -> Tuple[Dict[str, Dict[bool, Mapping[str, object]]], Dict[str, str]]:
    if not parquet_path.exists():
        raise FileNotFoundError(f"Summary Parquet file does not exist: {parquet_path}")
    table = pq.read_table(parquet_path)
    metadata = decode_metadata(table.schema.metadata)
    by_video: Dict[str, Dict[bool, Mapping[str, object]]] = defaultdict(dict)
    for entry in table.to_pylist():
        video_name = entry.get("video_name") or ""
        video_id = Path(video_name).stem
        if not video_id:
            raise ValueError(
                f"Unable to infer video identifier from video_name='{video_name}' in {parquet_path}"
            )
        stabilized = bool(entry.get("stabilizer_enabled", False))
        payload_raw = entry.get("payload_json")
        if payload_raw is None:
            raise ValueError(
                f"Missing payload_json for video {video_name} (stabilized={stabilized})"
            )
        payload = json.loads(payload_raw)
        if stabilized in by_video[video_id]:
            raise ValueError(
                f"Duplicate run detected for video {video_id} (stabilized={stabilized}) in {parquet_path}"
            )
        by_video[video_id][stabilized] = payload
    return dict(by_video), metadata


def _auto_cast(value: Optional[str]) -> Optional[object]:
    if value is None:
        return None
    if isinstance(value, str):
        normalized = value.strip()
        if not normalized:
            return None
        lowered = normalized.lower()
        if lowered == "none":
            return None
        if lowered == "true":
            return True
        if lowered == "false":
            return False
        try:
            if any(ch in normalized for ch in (".", "e", "E")):
                return float(normalized)
            return int(normalized)
        except ValueError:
            return normalized
    return value


def finite_values(values: Iterable[Optional[float]]) -> List[float]:
    cleaned: List[float] = []
    for value in values:
        if value is None:
            continue
        if isinstance(value, (int, float)):
            value = float(value)
            if math.isnan(value):
                continue
            cleaned.append(value)
    return cleaned


def load_pathway_summary(samples: Mapping[str, object], pathway: str) -> Dict[str, Optional[float]]:
    if pathway not in samples:
        raise KeyError(f"Pathway '{pathway}' missing in inference JSON")
    block = samples[pathway]
    summary: Dict[str, Optional[float]] = {}
    for metric in METRICS:
        summary[f"mean_{metric}"] = float(block.get(f"mean_{metric}"))
        summary[f"var_{metric}"] = _clip_variance(block.get(f"var_{metric}"))
    summary["coverage"] = _safe_float(block.get("coverage"))
    return summary


def _safe_float(value: Optional[float]) -> Optional[float]:
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _clip_variance(value: Optional[object]) -> Optional[float]:
    """
    Collapse per-frame variance samples into the variance of the clip-level mean.

    When ``value`` is an iterable of per-frame variances, treat the clip statistic as an
    equally-weighted mean across valid entries. For equal weights ``w_i = 1/n``,
    the variance of the mean is ``Σ(w_i^2 * var_i) = Σ(var_i) / n²``. Scalar inputs fall
    back to the regular float coercion path. Negative or non-finite values are ignored.
    """
    if value is None:
        return None
    if isinstance(value, (int, float)):
        try:
            coerced = float(value)
        except (TypeError, ValueError):
            return None
        return coerced if math.isfinite(coerced) and coerced >= 0.0 else None

    if isinstance(value, (str, bytes)):
        return _safe_float(value)

    try:
        iter_values = list(value)  # type: ignore[arg-type]
    except TypeError:
        return _safe_float(value)

    finite_variances: List[float] = []
    for entry in iter_values:
        if isinstance(entry, (int, float)):
            var = float(entry)
            if math.isfinite(var) and var >= 0.0:
                finite_variances.append(var)

    if not finite_variances:
        return None

    n = len(finite_variances)
    if n == 0:
        return None
    weight_sq = (1.0 / n) ** 2
    total = sum(var * weight_sq for var in finite_variances)
    return total


def summarize_run(
    video_id: str,
    inference: Mapping[str, object],
    labels: Mapping[str, float],
    stabilized: bool,
) -> Dict[str, object]:
    samples = inference.get("samples")
    if not isinstance(samples, Mapping):
        raise ValueError(f"Inference JSON for {video_id} missing 'samples' block")
    run_summary: Dict[str, object] = {
        "video_id": video_id,
        "Stablization": stabilized,
        "gt": dict(labels),
        "metrics": {},
        "coverage": {},
        "variances": {},
        "means": {},
    }
    for pathway in PATHWAYS:
        pathway_summary = load_pathway_summary(samples, pathway)
        run_summary["coverage"][pathway] = pathway_summary.get("coverage")
        run_summary["metrics"].setdefault(pathway, {})
        run_summary["variances"].setdefault(pathway, {})
        run_summary["means"].setdefault(pathway, {})
        for metric in METRICS:
            mean_key = f"mean_{metric}"
            mean_value = pathway_summary[mean_key]
            run_summary["means"][pathway][metric] = mean_value
            run_summary["metrics"][pathway][metric] = abs(mean_value - labels[metric])
            run_summary["variances"][pathway][metric] = pathway_summary.get(f"var_{metric}")
    return run_summary


def build_per_video_rows(
    video_data: Mapping[str, MutableMapping[bool, Dict[str, object]]],
    export_timestamp: str,
) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for video_id in sorted(video_data):
        runs = video_data[video_id]
        if True not in runs or False not in runs:
            raise ValueError(f"Video {video_id} missing stabilized or unstabilized run")
        run_rows: Dict[bool, Dict[str, object]] = {}
        for stabilized_flag, run_summary in runs.items():
            row: Dict[str, object] = {
                "video_id": video_id,
                "Stablization": stabilized_flag,
                "gt_mean_valence": run_summary["gt"]["valence"],
                "gt_mean_arousal": run_summary["gt"]["arousal"],
            }
            for pathway in PATHWAYS:
                row[f"coverage_{pathway}"] = run_summary["coverage"].get(pathway)
                for metric in METRICS:
                    row[f"mean_{pathway}_{metric}"] = run_summary["means"][pathway][metric]
                    row[f"mae_{pathway}_{metric}"] = run_summary["metrics"][pathway][metric]
                    row[f"var_{pathway}_{metric}"] = run_summary["variances"][pathway][metric]
            fused_variances = run_summary["variances"].get("fusion", {})
            fused_valence_var = fused_variances.get("valence")
            fused_arousal_var = fused_variances.get("arousal")
            row["valence_std_dev"] = (
                math.sqrt(fused_valence_var) if fused_valence_var is not None and fused_valence_var >= 0.0 else None
            )
            row["arousal_std_dev"] = (
                math.sqrt(fused_arousal_var) if fused_arousal_var is not None and fused_arousal_var >= 0.0 else None
            )
            row["export_timestamp"] = export_timestamp
            run_rows[stabilized_flag] = row
        for metric in METRICS:
            face_key = f"mae_face_{metric}"
            scene_key = f"mae_scene_{metric}"
            fusion_key = f"mae_fusion_{metric}"
            for stabilized_flag, row in run_rows.items():
                row[f"face_beats_fusion_{metric}"] = row[face_key] < row[fusion_key]
                row[f"scene_beats_fusion_{metric}"] = row[scene_key] < row[fusion_key]
        for pathway in PATHWAYS:
            for metric in METRICS:
                delta = (
                    run_rows[True][f"mae_{pathway}_{metric}"]
                    - run_rows[False][f"mae_{pathway}_{metric}"]
                )
                run_rows[True][f"delta_mae_{pathway}_{metric}"] = delta
                run_rows[False][f"delta_mae_{pathway}_{metric}"] = delta
        rows.append(run_rows[False])
        rows.append(run_rows[True])
    return rows


def bootstrap_ci(
    values: List[float],
    rng: random.Random,
    bootstrap_samples: int,
    ci: float,
) -> List[float]:
    if not values:
        return [math.nan, math.nan]
    if len(values) == 1:
        return [values[0], values[0]]
    stats: List[float] = []
    sample_size = len(values)
    for _ in range(bootstrap_samples):
        sample = [values[rng.randrange(sample_size)] for _ in range(sample_size)]
        stats.append(sum(sample) / sample_size)
    stats.sort()
    alpha = (1.0 - ci) / 2.0
    lower_index = max(0, int(math.floor(alpha * (len(stats) - 1))))
    upper_index = max(0, int(math.ceil((1.0 - alpha) * (len(stats) - 1))))
    upper_index = min(upper_index, len(stats) - 1)
    return [stats[lower_index], stats[upper_index]]


def aggregate_dataset_rows(
    video_data: Mapping[str, MutableMapping[bool, Dict[str, object]]],
    rng: random.Random,
    bootstrap_samples: int,
    ci: float,
    export_timestamp: str,
) -> List[Dict[str, object]]:
    aggregates: List[Dict[str, object]] = []
    for pathway in PATHWAYS:
        for metric in METRICS:
            stabilized_values: List[float] = []
            raw_values: List[float] = []
            coverage_stabilized: List[float] = []
            coverage_raw: List[float] = []
            variance_stabilized: List[float] = []
            variance_raw: List[float] = []
            delta_values: List[float] = []
            for video_id in video_data:
                runs = video_data[video_id]
                if True not in runs or False not in runs:
                    continue
                stabilized_run = runs[True]
                raw_run = runs[False]
                stabilized_values.append(
                    stabilized_run["metrics"][pathway][metric]
                )
                raw_values.append(raw_run["metrics"][pathway][metric])
                coverage_stabilized.append(
                    stabilized_run["coverage"].get(pathway)
                )
                coverage_raw.append(raw_run["coverage"].get(pathway))
                variance_stabilized.append(
                    stabilized_run["variances"][pathway][metric]
                )
                variance_raw.append(
                    raw_run["variances"][pathway][metric]
                )
                delta_values.append(
                    stabilized_run["metrics"][pathway][metric]
                    - raw_run["metrics"][pathway][metric]
                )
            cleaned_stabilized = finite_values(stabilized_values)
            cleaned_raw = finite_values(raw_values)
            cleaned_delta = finite_values(delta_values)
            coverage_stabilized = finite_values(coverage_stabilized)
            coverage_raw = finite_values(coverage_raw)
            variance_stabilized = finite_values(variance_stabilized)
            variance_raw = finite_values(variance_raw)
            row: Dict[str, object] = {
                "pathway": pathway,
                "metric": metric,
                "count": len(cleaned_stabilized),
                "mae_mean_stabilized": _mean(cleaned_stabilized),
                "mae_mean_unstabilized": _mean(cleaned_raw),
                "mae_median_stabilized": _median(cleaned_stabilized),
                "mae_median_unstabilized": _median(cleaned_raw),
                "mae_std_stabilized": _stdev(cleaned_stabilized),
                "mae_std_unstabilized": _stdev(cleaned_raw),
                "mae_ci_low_stabilized": math.nan,
                "mae_ci_high_stabilized": math.nan,
                "mae_ci_low_unstabilized": math.nan,
                "mae_ci_high_unstabilized": math.nan,
                "delta_mae_mean": _mean(cleaned_delta),
                "delta_mae_median": _median(cleaned_delta),
                "delta_mae_ci_low": math.nan,
                "delta_mae_ci_high": math.nan,
                "coverage_mean_stabilized": _mean(coverage_stabilized),
                "coverage_mean_unstabilized": _mean(coverage_raw),
                "coverage_std_stabilized": _stdev(coverage_stabilized),
                "coverage_std_unstabilized": _stdev(coverage_raw),
                "variance_mean_stabilized": _mean(variance_stabilized),
                "variance_mean_unstabilized": _mean(variance_raw),
                "export_timestamp": export_timestamp,
            }
            row["mae_ci_low_stabilized"], row["mae_ci_high_stabilized"] = bootstrap_ci(
                cleaned_stabilized, rng, bootstrap_samples, ci
            )
            row["mae_ci_low_unstabilized"], row["mae_ci_high_unstabilized"] = bootstrap_ci(
                cleaned_raw, rng, bootstrap_samples, ci
            )
            row["delta_mae_ci_low"], row["delta_mae_ci_high"] = bootstrap_ci(
                cleaned_delta, rng, bootstrap_samples, ci
            )
            aggregates.append(row)
    return aggregates


def _mean(values: List[float]) -> float:
    if not values:
        return math.nan
    return statistics.fmean(values)


def _median(values: List[float]) -> float:
    if not values:
        return math.nan
    return statistics.median(values)


def _stdev(values: List[float]) -> float:
    if len(values) <= 1:
        return math.nan
    return statistics.stdev(values)


def write_csv(path: Path, rows: List[Dict[str, object]], fieldnames: List[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def write_json(path: Path, payload: Mapping[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True)
        handle.write("\n")


def main() -> None:
    args = parse_args()
    summary_parquet = args.summary_parquet
    labels_dir = args.labels_dir
    if not labels_dir.exists():
        raise FileNotFoundError(f"Required directory does not exist: {labels_dir}")
    video_payloads, metadata = load_pipeline_runs(summary_parquet)
    if not video_payloads:
        raise ValueError(f"No runs found inside {summary_parquet}")
    inferred_timestamp = metadata.get("timestamp")
    export_timestamp = args.timestamp or inferred_timestamp or datetime.now(UTC).strftime(
        "%Y%m%d_%H%M%S"
    )
    rng = random.Random(args.seed)
    video_data: Dict[str, MutableMapping[bool, Dict[str, object]]] = {}
    for video_id in sorted(video_payloads):
        runs = video_payloads[video_id]
        if True not in runs or False not in runs:
            raise ValueError(
                f"Video {video_id} missing stabilized or unstabilized run in {summary_parquet}"
            )
        labels = load_ground_truth_means(labels_dir, video_id)
        video_data[video_id] = {
            True: summarize_run(video_id, runs[True], labels, True),
            False: summarize_run(video_id, runs[False], labels, False),
        }
    def _metadata_value(key: str, default: object) -> object:
        return _auto_cast(metadata.get(key)) if key in metadata else default

    run_parameters: Dict[str, object] = {
        "VIDEO_DIR": "data/VEATIC/videos",
        "OUTPUT_ROOT": "results/inference",
        "VIDEO_EXTENSIONS": [".mp4", ".mov", ".mkv", ".avi"],
        "SCENE_TTA": _metadata_value("scene_tta", 3),
        "FACE_TTA": _metadata_value("face_tta", 3),
        "TARGET_SAMPLE_FPS": _metadata_value("target_sample_fps", 1.0),
        "MAX_FRAMES": _metadata_value("max_frames", None),
        "USE_VARIANCE_WEIGHTING": _metadata_value("use_variance_weighting", True),
        "SCENE_WEIGHT": _metadata_value("scene_weight", 0.6),
        "FACE_WEIGHT": _metadata_value("face_weight", 0.4),
        "FACE_SCORE_THRESHOLD": _metadata_value("face_score_threshold", None),
        "FACE_MAX_SIGMA": _metadata_value("face_max_sigma", None),
        "BRIGHTNESS_THRESHOLD": _metadata_value("brightness_threshold", None),
        "STABILIZER_MODE": _metadata_value("stabilizer_mode", "both"),
        "UNCERTAINTY_THRESHOLD": 0.4,
        "STABILIZER_WINDOW": 60,
        "STABILIZER_ALPHA": 0.7,
        "BATCH_EXPORT_MODES": ["unstabilized", "stabilized"],
        "SUMMARY_PARQUET": str(summary_parquet),
        "PIPELINE_COMMAND": metadata.get("command"),
        "PIPELINE_TIMESTAMP": metadata.get("timestamp"),
        "EVALUATION_TIMESTAMP": export_timestamp,
        "VIDEO_COUNT": len(video_payloads),
        "VIDEOS_INCLUDED": sorted(video_payloads.keys()),
    }
    per_video_rows = build_per_video_rows(video_data, export_timestamp)
    per_video_columns: List[str] = [
        "video_id",
        "Stablization",
        "gt_mean_valence",
        "gt_mean_arousal",
    ]
    for pathway in PATHWAYS:
        for metric in METRICS:
            per_video_columns.append(f"mean_{pathway}_{metric}")
        per_video_columns.append(f"coverage_{pathway}")
        for metric in METRICS:
            per_video_columns.append(f"mae_{pathway}_{metric}")
        for metric in METRICS:
            per_video_columns.append(f"var_{pathway}_{metric}")
    per_video_columns.append("valence_std_dev")
    per_video_columns.append("arousal_std_dev")
    for metric in METRICS:
        per_video_columns.append(f"face_beats_fusion_{metric}")
        per_video_columns.append(f"scene_beats_fusion_{metric}")
    for pathway in PATHWAYS:
        for metric in METRICS:
            per_video_columns.append(f"delta_mae_{pathway}_{metric}")
    per_video_columns.append("export_timestamp")
    aggregates = aggregate_dataset_rows(
        video_data,
        rng=rng,
        bootstrap_samples=args.bootstrap_samples,
        ci=args.ci,
        export_timestamp=export_timestamp,
    )
    aggregate_columns: List[str] = [
        "pathway",
        "metric",
        "count",
        "mae_mean_stabilized",
        "mae_mean_unstabilized",
        "mae_median_stabilized",
        "mae_median_unstabilized",
        "mae_std_stabilized",
        "mae_std_unstabilized",
        "mae_ci_low_stabilized",
        "mae_ci_high_stabilized",
        "mae_ci_low_unstabilized",
        "mae_ci_high_unstabilized",
        "delta_mae_mean",
        "delta_mae_median",
        "delta_mae_ci_low",
        "delta_mae_ci_high",
        "coverage_mean_stabilized",
        "coverage_mean_unstabilized",
        "coverage_std_stabilized",
        "coverage_std_unstabilized",
        "variance_mean_stabilized",
        "variance_mean_unstabilized",
        "export_timestamp",
    ]
    output_dir = args.output_dir
    per_video_path = output_dir / f"veatic_per_video_{export_timestamp}.csv"
    aggregate_path = output_dir / f"veatic_aggregate_{export_timestamp}.csv"
    params_path = output_dir / f"veatic_run_params_{export_timestamp}.json"
    write_csv(per_video_path, per_video_rows, per_video_columns)
    write_csv(aggregate_path, aggregates, aggregate_columns)
    write_json(params_path, run_parameters)
    print(f"Wrote per-video metrics to {per_video_path}")
    print(f"Wrote aggregate metrics to {aggregate_path}")
    print(f"Wrote run parameters to {params_path}")


if __name__ == "__main__":
    main()
# Over-engineering check: Direct Parquet ingestion removes redundant JSON I/O without extra complexity; bootstrap CI still optional for quicker runs.
